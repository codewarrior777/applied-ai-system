"""
LLM Agent for parsing natural language tasks in PawPal+.
Uses OpenRouter (via the OpenAI SDK) to extract structured JSON.
Includes a Regex fallback for maximum reliability.
"""

import json
import logging
import os
import re

from dotenv import load_dotenv
from openai import OpenAI

from nl_parser import ParsedTask
from nl_parser import parse_task as regex_parse_task

# Configure logging for debugging and error tracking
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# Ensure environment variables (.env) are loaded
load_dotenv()

# OpenRouter client configuration
client = OpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=os.getenv("OPENROUTER_API_KEY", ""),
)

# Current model
MODEL = "recursive/flint-v1.0:free"


def parse_task_with_llm(text: str, known_pets: list[str]) -> ParsedTask:
    """AI Agent with Guardrails and Fallback."""

    # Guardrail 0: Check if the API Key exists and is not a placeholder
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key or api_key.strip() == "" or api_key == "dummy_key":
        logger.warning("[Guardrail] API Key not found. Using Regex parser.")
        return regex_parse_task(text, known_pets)

    system_prompt = f"""
    You are an AI assistant for a pet care app. Extract task details from the user's text.
    Return ONLY a valid JSON object with these exact keys:
    - "description": (string) What the task is. Keep the pet's name in it.
    - "time": (string) 24-hour format "HH:MM" (e.g., "07:00", "18:30"). If no time is found, use "12:00".
    - "frequency": (string) "once", "daily", or "weekly".
    - "priority": (string) "high", "medium", or "low". If no priority is found, use "medium".
    - "pet_name": (string or null) One of these exact names: {known_pets}.
    
    Do not include markdown formatting like ```json.
    """

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": text},
            ],
            temperature=0.1,
            max_tokens=150,
        )

        raw_json = response.choices[0].message.content.strip()

        # Guardrail 1: Clean markdown formatting from the LLM response
        raw_json = re.sub(r"^```(json)?", "", raw_json, flags=re.IGNORECASE).strip()
        raw_json = re.sub(r"```$", "", raw_json).strip()

        data = json.loads(raw_json)

        # Guardrail 2: Validate time
        time_val = data.get("time", "12:00")
        if not re.match(r"^(0[0-9]|1[0-9]|2[0-3]):[0-5][0-9]$", str(time_val)):
            logger.warning(
                f"[Guardrail] Invalid time generated by AI: {time_val}. Using 12:00."
            )
            time_val = "12:00"

        # Guardrail 3: Validate pet name
        pet_val = data.get("pet_name")
        if pet_val not in known_pets:
            pet_val = None

        # Guardrail 4: Validate frequency and priority
        freq_val = data.get("frequency", "once")
        if freq_val not in ["once", "daily", "weekly"]:
            freq_val = "once"

        prio_val = data.get("priority", "medium")
        if prio_val not in ["high", "medium", "low"]:
            prio_val = "medium"

        logger.info("[Agentic AI] Task successfully extracted by the LLM.")
        return ParsedTask(
            description=data.get("description", "Task"),
            time=time_val,
            frequency=freq_val,
            priority=prio_val,
            pet_name=pet_val,
        )

    except Exception as e:  # noqa: BLE001
        # Fallback: If the API fails (404, 429, timeout, etc.), use Regex and don't crash.
        logger.error(f"[Guardrail] LLM error ({e}). Using Regex parser (Fallback).")
        return regex_parse_task(text, known_pets)